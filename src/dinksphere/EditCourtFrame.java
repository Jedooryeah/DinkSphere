    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
    
String courtName = txtCourtName.getText().trim();
String category = cmbCategory.getSelectedItem().toString();
String rateText = txtRate.getText().trim();
String status = cmbStatus.getSelectedItem().toString();

if (courtName.isEmpty() || rateText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please complete all required fields.");
    return;
}

java.math.BigDecimal rate;

try {
    rate = new java.math.BigDecimal(rateText);

    if (rate.compareTo(java.math.BigDecimal.ZERO) <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Hourly rate must be greater than zero.");
        return;
    }
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter a valid hourly rate.");
    return;
}

String sql = "UPDATE tbl_courts SET court_name = ?, "
        + "court_category = ?, rate_per_hour = ?, "
        + "status = ?, image_path = ? WHERE id = ?";

try (java.sql.Connection conn = DBConnection.connect()) {
    if (conn == null) {
        return;
    }

    try (java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {
        pst.setString(1, courtName);
        pst.setString(2, category);
        pst.setBigDecimal(3, rate);
        pst.setString(4, status);
        pst.setString(5, selectedImagePath);
        pst.setInt(6, courtId);

        pst.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
                this, "Court updated successfully!");

        dispose();
    }
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to update court: " + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_btnSaveActionPerformed

