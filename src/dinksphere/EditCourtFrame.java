private void loadCourtDetails() {
    String sql = "SELECT court_name, court_category, "
            + "rate_per_hour, status, image_path "
            + "FROM tbl_courts WHERE id = ?";

    try (java.sql.Connection conn = DBConnection.connect()) {
        if (conn == null) {
            return;
        }

        try (java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setInt(1, courtId);

            try (java.sql.ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    txtCourtName.setText(rs.getString("court_name"));
                    cmbCategory.setSelectedItem(rs.getString("court_category"));
                    txtRate.setText(rs.getBigDecimal("rate_per_hour").toString());
                    cmbStatus.setSelectedItem(rs.getString("status"));

                    selectedImagePath = rs.getString("image_path");

                    if (selectedImagePath != null
                            && !selectedImagePath.isEmpty()) {
                        java.io.File imageFile =
                                new java.io.File(selectedImagePath);

                        if (imageFile.exists()) {
                            java.awt.Image image =
                                    javax.imageio.ImageIO.read(imageFile);

                            if (image != null) {
                                java.awt.Image scaledImage =
                                        image.getScaledInstance(
                                                lblCourtImage.getWidth(),
                                                lblCourtImage.getHeight(),
                                                java.awt.Image.SCALE_SMOOTH);

                                lblCourtImage.setIcon(
                                        new javax.swing.ImageIcon(scaledImage));
                                lblCourtImage.setText("");
                            }
                        }
                    }
                } else {
                    javax.swing.JOptionPane.showMessageDialog(
                            this, "Court record not found.");
                    dispose();
                }
            }
        }

    } catch (java.sql.SQLException | java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to load court details: " + e.getMessage(),
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}


