    private void loadMyBookings() {

    String sql =
            "SELECT id, court_name, booking_date, "
            + "start_time, end_time, payment_status, status, "
            + "rejection_reason "
            + "FROM tbl_bookings "
            + "WHERE user_id = ? "
            + "ORDER BY booking_date DESC, start_time ASC";

    try {

        Connection conn = DBConnection.connect();

        if (conn == null) {
            return;
        }

        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setInt(1, Session.userId);

        ResultSet rs = pst.executeQuery();

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblMyBookings.getModel();

        model.setRowCount(0);

        java.text.SimpleDateFormat dateFormat =
                new java.text.SimpleDateFormat("MM/dd/yyyy");

        java.text.SimpleDateFormat timeFormat =
                new java.text.SimpleDateFormat("h:mm a");

        while (rs.next()) {

            String date = dateFormat.format(
                    rs.getDate("booking_date")
            );

            String startTime = timeFormat.format(
                    rs.getTime("start_time")
            );

            String endTime = timeFormat.format(
                    rs.getTime("end_time")
            );

            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("court_name"),
                date,
                startTime,
                endTime,
                rs.getString("payment_status"),
                rs.getString("status"),
                rs.getString("rejection_reason") == null
                        ? "-"
                        : rs.getString("rejection_reason")
            });
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to load your bookings: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

        
    }

