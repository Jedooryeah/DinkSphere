private void loadBookingDetails(int bookingId) {

    String sql =
            "SELECT b.id, u.fullname, b.court_name, "
            + "b.booking_date, b.start_time, b.end_time, "
            + "b.payment_status, b.status "
            + "FROM tbl_bookings b "
            + "INNER JOIN tbl_users u ON b.user_id = u.id "
            + "WHERE b.id = ? AND b.user_id = ?";

    try {

        java.sql.Connection conn = DBConnection.connect();

        if (conn == null) {
            return;
        }

        java.sql.PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setInt(1, bookingId);
        pst.setInt(2, Session.userId);

        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            String status = rs.getString("status");
            String paymentStatus = rs.getString("payment_status");

            lblBookingId.setText(
                    "Booking ID: #" + rs.getInt("id")
            );

            lblPlayerName.setText(
                    "Player: " + rs.getString("fullname")
            );

            lblCourt.setText(
                    "Court: " + rs.getString("court_name")
            );

            java.text.SimpleDateFormat dateFormat =
                    new java.text.SimpleDateFormat("MMMM dd, yyyy");

            java.text.SimpleDateFormat timeFormat =
                    new java.text.SimpleDateFormat("h:mm a");

            lblDate.setText(
                    "Date: " + dateFormat.format(
                            rs.getDate("booking_date")
                    )
            );

            lblStartTime.setText(
                    "Start Time: " + timeFormat.format(
                            rs.getTime("start_time")
                    )
            );

            lblEndTime.setText(
                    "End Time: " + timeFormat.format(
                            rs.getTime("end_time")
                    )
            );

            lblPaymentStatus.setText(
            "Payment Status: " + paymentStatus
            );

            if ("Rejected".equalsIgnoreCase(paymentStatus)) {
            lblPaymentStatus.setForeground(java.awt.Color.RED);
            } else if ("Paid".equalsIgnoreCase(paymentStatus)) {
            lblPaymentStatus.setForeground(new java.awt.Color(0, 153, 0));
            } else {
            lblPaymentStatus.setForeground(java.awt.Color.BLACK);
            }

            // Only confirmed and paid bookings are valid for presentation.
            boolean validBooking =
                    "Confirmed".equalsIgnoreCase(status)
                    && "Paid".equalsIgnoreCase(paymentStatus);

            if (validBooking) {
                lblSubtitle.setText("CONFIRMED BOOKING");
            } else {
                lblSubtitle.setText(
                        "NOT VALID FOR COURT ENTRY - "
                        + status.toUpperCase()
                );
            }

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Booking not found or it does not belong to your account.",
                    "Booking Details",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            dispose();
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to load booking details: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

}


