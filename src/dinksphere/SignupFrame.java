    private void createaccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createaccountActionPerformed
    String fullName = SFullname.getText().trim();
    String username = SUsername.getText().trim();
    String email = SEmail.getText().trim();
    String password = new String(SPassword.getPassword());
    String confirmPassword = new String(SConfirmpassword.getPassword());

if (fullName.isEmpty() || username.isEmpty() || email.isEmpty()
        || password.isEmpty() || confirmPassword.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please fill in all fields.",
        "Sign Up",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

    return;
}

if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please enter a valid email address.",
        "Invalid Email",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    SEmail.requestFocus();
    return;
}

if (!username.matches("[A-Za-z0-9_]{4,20}")) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Username must be 4–20 characters and contain only letters, numbers, or underscores.",
        "Invalid Username",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    SUsername.requestFocus();
    return;
}

if (password.length() < 7) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Password must contain at least 7 characters.",
        "Weak Password",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    SPassword.requestFocus();
    return;
}




if (!password.equals(confirmPassword)) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Passwords do not match.",
        "Sign Up",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

    return;
}

try {

    Connection conn = DBConnection.connect();

    
    String checkSql =
        "SELECT * FROM tbl_users WHERE username = ? OR email = ?";


    java.sql.PreparedStatement checkPst =
            conn.prepareStatement(checkSql);

        checkPst.setString(1, username);
        checkPst.setString(2, email);

    java.sql.ResultSet rs = checkPst.executeQuery();

    if (rs.next()) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Username or email is already registered.",
            "Sign Up",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        rs.close();
        checkPst.close();
        conn.close();

        return;
    }

    rs.close();
    checkPst.close();

    String sql =
            "INSERT INTO tbl_users "
            + "(fullname, username, email, password, role) "
            + "VALUES (?, ?, ?, ?, ?)";

    java.sql.PreparedStatement pst =
            conn.prepareStatement(sql);

    pst.setString(1, fullName);
    pst.setString(2, username);
    pst.setString(3, email);
    String hashedPassword = BCrypt.hashpw(password, BCrypt.gensalt(12));
    pst.setString(4, hashedPassword);
    pst.setString(5, "Player");

    pst.executeUpdate();

    pst.close();
    conn.close();

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Account created successfully!",
        "Sign Up",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    LoginFrame login = new LoginFrame();
    login.setVisible(true);
    this.dispose();

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Database error: " + e.getMessage(),
        "Database Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_createaccountActionPerformed

