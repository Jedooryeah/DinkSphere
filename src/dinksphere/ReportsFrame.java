private void loadReports() {
    Date fromDate = dateFromChooser.getDate();
    Date toDate = dateToChooser.getDate();

    if (fromDate == null || toDate == null) {
        JOptionPane.showMessageDialog(
                this,
                "Please select both start and end dates."
        );
        return;
    }

    if (fromDate.after(toDate)) {
        JOptionPane.showMessageDialog(
                this,
                "Start date cannot be after end date."
        );
        return;
    }

    String sql = "SELECT "
            + "COUNT(*) AS total, "
            + "SUM(CASE WHEN status = 'Pending' THEN 1 ELSE 0 END) AS pending, "
            + "SUM(CASE WHEN status = 'Confirmed' THEN 1 ELSE 0 END) AS confirmed, "
            + "SUM(CASE WHEN status = 'Rejected' THEN 1 ELSE 0 END) AS rejected "
            + "FROM tbl_bookings "
            + "WHERE booking_date BETWEEN ? AND ?";

    try (Connection conn = DBConnection.connect()) {
        if (conn == null) {
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setDate(1, new java.sql.Date(fromDate.getTime()));
            pst.setDate(2, new java.sql.Date(toDate.getTime()));

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    lblTotalBookings.setText(
                            String.valueOf(rs.getInt("total"))
                    );

                    lblPendingBookings.setText(
                            String.valueOf(rs.getInt("pending"))
                    );

                    lblConfirmedBookings.setText(
                            String.valueOf(rs.getInt("confirmed"))
                    );

                    lblRejectedBookings.setText(
                            String.valueOf(rs.getInt("rejected"))
                    );
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Failed to load reports: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

    loadRevenue(fromDate, toDate);
}

private void loadRevenue(Date fromDate, Date toDate) {
    String sql = "SELECT COALESCE(SUM("
            + "c.rate_per_hour * "
            + "TIME_TO_SEC(TIMEDIFF(b.end_time, b.start_time)) / 3600"
            + "), 0) AS revenue "
            + "FROM tbl_bookings b "
            + "JOIN tbl_courts c ON c.court_name = b.court_name "
            + "WHERE b.booking_date BETWEEN ? AND ? "
            + "AND b.payment_status = 'Paid' "
            + "AND b.status = 'Confirmed'";

    try (Connection conn = DBConnection.connect()) {
        if (conn == null) {
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setDate(1, new java.sql.Date(fromDate.getTime()));
            pst.setDate(2, new java.sql.Date(toDate.getTime()));

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    BigDecimal revenue = rs.getBigDecimal("revenue");

                    lblTotalRevenue.setText(
                            "₱" + revenue.setScale(
                                    2, java.math.RoundingMode.HALF_UP
                            ).toPlainString()
                    );
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Failed to load revenue: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}



