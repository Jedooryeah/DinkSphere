private void loadUsers() {
    String sql = "SELECT id, fullname, username, email, role "
               + "FROM tbl_users ORDER BY id ASC";

    try {
        Connection conn = DBConnection.connect();

        if (conn == null) {
            return;
        }

        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        DefaultTableModel model =
                (DefaultTableModel) tblUsers.getModel();

        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("fullname"),
                rs.getString("username"),
                rs.getString("email"),
                rs.getString("role")
            });
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Failed to load users: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
    
private void searchUsers() {
    String keyword = txtSearchUsers.getText().trim();

    String sql = "SELECT id, fullname, username, email, role "
            + "FROM tbl_users "
            + "WHERE fullname LIKE ? "
            + "OR username LIKE ? "
            + "OR email LIKE ? "
            + "ORDER BY id ASC";

    try (Connection conn = DBConnection.connect()) {
        if (conn == null) {
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {
            String searchValue = "%" + keyword + "%";

            pst.setString(1, searchValue);
            pst.setString(2, searchValue);
            pst.setString(3, searchValue);

            try (ResultSet rs = pst.executeQuery()) {
                DefaultTableModel model =
                        (DefaultTableModel) tblUsers.getModel();

                model.setRowCount(0);

                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("id"),
                        rs.getString("fullname"),
                        rs.getString("username"),
                        rs.getString("email"),
                        rs.getString("role")
                    });
                }
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Search failed: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}


