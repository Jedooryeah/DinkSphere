    private void btnViewProofActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewProofActionPerformed
    int selectedRow = tblPendingPayments.getSelectedRow();

    if (selectedRow == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a booking first.",
                "Payment Proof",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int bookingId =
            Integer.parseInt(
                    tblPendingPayments
                            .getValueAt(selectedRow, 0)
                            .toString()
            );

    String sql =
            "SELECT payment_proof "
            + "FROM tbl_bookings "
            + "WHERE id = ?";

    try {

        java.sql.Connection conn =
                DBConnection.connect();

        java.sql.PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setInt(1, bookingId);

        java.sql.ResultSet rs =
                pst.executeQuery();

        if (rs.next()) {

            String paymentProof =
                    rs.getString("payment_proof");

            if (paymentProof == null ||
                    paymentProof.trim().isEmpty()) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No payment proof was uploaded for this booking.",
                        "Payment Proof",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );

            } else {

                java.io.File proofFile =
                        new java.io.File(
                                "payment_proofs",
                                paymentProof
                        );

                if (!proofFile.exists()) {

                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Payment proof file could not be found.",
                            "Payment Proof",
                            javax.swing.JOptionPane.ERROR_MESSAGE
                    );

                } else {

                    javax.swing.ImageIcon originalIcon =
        new javax.swing.ImageIcon(
                proofFile.getAbsolutePath()
        );

int maxWidth = 600;
int maxHeight = 600;

int originalWidth = originalIcon.getIconWidth();
int originalHeight = originalIcon.getIconHeight();

double scale = Math.min(
        (double) maxWidth / originalWidth,
        (double) maxHeight / originalHeight
);

int newWidth =
        (int) (originalWidth * scale);

int newHeight =
        (int) (originalHeight * scale);

java.awt.Image resizedImage =
        originalIcon.getImage().getScaledInstance(
                newWidth,
                newHeight,
                java.awt.Image.SCALE_SMOOTH
        );

javax.swing.ImageIcon imageIcon =
        new javax.swing.ImageIcon(resizedImage);

javax.swing.JLabel imageLabel =
        new javax.swing.JLabel(imageIcon);

                    javax.swing.JScrollPane scrollPane =
                            new javax.swing.JScrollPane(imageLabel);

                    javax.swing.JDialog dialog =
                            new javax.swing.JDialog(
                                    this,
                                    "Payment Proof",
                                    true
                            );

                    dialog.setSize(700, 700);
                    dialog.setLocationRelativeTo(this);

                    dialog.add(scrollPane);

                    dialog.setVisible(true);
                }
            }
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to load payment proof: "
                + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnViewProofActionPerformed

