    private void loadPendingPayments() {

    String sql =
            "SELECT b.id, u.fullname, b.court_name, "
            + "b.booking_date, b.start_time, b.end_time, "
            + "b.payment_method, b.payment_reference, "
            + "b.payment_status, b.status "
            + "FROM tbl_bookings b "
            + "INNER JOIN tbl_users u ON b.user_id = u.id "
            + "WHERE b.status = 'Pending' "
            + "ORDER BY b.booking_date ASC, b.start_time ASC";

    try {

        Connection conn = DBConnection.connect();

        PreparedStatement pst =
                conn.prepareStatement(sql);

        ResultSet rs = pst.executeQuery();

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblPendingPayments.getModel();

        model.setRowCount(0);

        java.text.SimpleDateFormat dateFormat =
                new java.text.SimpleDateFormat("MM/dd/yyyy");

        java.text.SimpleDateFormat timeFormat =
                new java.text.SimpleDateFormat("h:mm a");

        while (rs.next()) {

            String formattedDate =
                    dateFormat.format(
                            rs.getDate("booking_date")
                    );

            String formattedStartTime =
                    timeFormat.format(
                            rs.getTime("start_time")
                    );

            String formattedEndTime =
                    timeFormat.format(
                            rs.getTime("end_time")
                    );

            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("fullname"),
                rs.getString("court_name"),
                formattedDate,
                formattedStartTime,
                formattedEndTime,
                rs.getString("payment_method"),
                rs.getString("payment_reference"),
                rs.getString("status")
        });
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to load pending payments: "
                + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}

