    private void btnRejectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRejectActionPerformed

    int selectedRow = tblPendingPayments.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a booking first.",
                "Reject Payment",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int bookingId = Integer.parseInt(
            tblPendingPayments
                    .getValueAt(selectedRow, 0)
                    .toString()
    );

    String reason = javax.swing.JOptionPane.showInputDialog(
            this,
            "Enter the reason for rejecting this payment:",
            "Reject Payment",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );

    // Cancel or close the input dialog
    if (reason == null) {
        return;
    }

    reason = reason.trim();

    if (reason.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter a rejection reason.",
                "Reject Payment",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Rejection reason:\n" + reason
            + "\n\nAre you sure you want to reject this payment?",
            "Confirm Rejection",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
    );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
            "UPDATE tbl_bookings "
            + "SET status = 'Rejected', "
            + "payment_status = 'Rejected', "
            + "rejection_reason = ? "
            + "WHERE id = ? AND status = 'Pending'";

    try {

        java.sql.Connection conn = DBConnection.connect();

        if (conn == null) {
            return;
        }

        java.sql.PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setString(1, reason);
        pst.setInt(2, bookingId);

        int updated = pst.executeUpdate();

        pst.close();
        conn.close();

        if (updated == 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "This booking is no longer pending. Please refresh the table.",
                    "Reject Payment",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            loadPendingPayments();
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Payment rejected successfully.",
                "Payment Rejected",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        loadPendingPayments();

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to reject payment: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnRejectActionPerformed

