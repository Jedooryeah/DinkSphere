    private void loadCourts() {
    String sql = "SELECT id, court_name, court_category, "
        + "rate_per_hour, status "
        + "FROM tbl_courts ORDER BY id ASC";
    
    
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblCourts.getModel();

    model.setRowCount(0);

    
try (java.sql.Connection conn = DBConnection.connect()) {
    if (conn == null) {
        return;
    }

    try (java.sql.PreparedStatement pst =
                 conn.prepareStatement(sql);
         java.sql.ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("court_name"),
                rs.getString("court_category"),
                rs.getBigDecimal("rate_per_hour"),
                rs.getString("status"),
                "Edit"
            });
        }
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to load courts: " + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }



