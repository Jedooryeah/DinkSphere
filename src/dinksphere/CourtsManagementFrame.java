    private void tblCourtsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCourtsMouseClicked

    int row = tblCourts.rowAtPoint(evt.getPoint());
    int column = tblCourts.columnAtPoint(evt.getPoint());

    if (row < 0) {
        return;
    }

    // Edit column
    if (column == 5) {
        int courtId = Integer.parseInt(
                tblCourts.getValueAt(row, 0).toString()
        );

        EditCourtFrame editFrame = new EditCourtFrame(courtId);

        editFrame.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                loadCourts();
            }
        });

        editFrame.setVisible(true);
    }
    }//GEN-LAST:event_tblCourtsMouseClicked

