    private void btnBrowseProofActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBrowseProofActionPerformed

    javax.swing.JFileChooser fileChooser =
            new javax.swing.JFileChooser();

    javax.swing.filechooser.FileNameExtensionFilter filter =
            new javax.swing.filechooser.FileNameExtensionFilter(
                    "Image Files",
                    "jpg",
                    "jpeg",
                    "png"
            );

    fileChooser.setFileFilter(filter);

    int result = fileChooser.showOpenDialog(this);

    if (result == javax.swing.JFileChooser.APPROVE_OPTION) {

        java.io.File selectedFile =
                fileChooser.getSelectedFile();

        txtPaymentProof.setText(
                selectedFile.getName()
        );

        try {

            java.io.File proofFolder =
                    new java.io.File("payment_proofs");

            if (!proofFolder.exists()) {
                proofFolder.mkdirs();
            }

            java.io.File destination =
                    new java.io.File(
                            proofFolder,
                            selectedFile.getName()
                    );

            java.nio.file.Files.copy(
                    selectedFile.toPath(),
                    destination.toPath(),
                    java.nio.file.StandardCopyOption.REPLACE_EXISTING
            );

        } catch (java.io.IOException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to save payment proof: "
                    + e.getMessage(),
                    "Upload Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }

    }//GEN-LAST:event_btnBrowseProofActionPerformed

