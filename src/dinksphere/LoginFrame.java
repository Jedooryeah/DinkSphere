    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
    
String username = Lusername.getText().trim();
String password = new String(Lpassword.getPassword());

if (username.isEmpty() || password.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please enter your username and password.",
        "Login",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

String sql = "SELECT * FROM tbl_users WHERE username = ?";

try (Connection conn = DBConnection.connect()) {

    if (conn == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to connect to the database.",
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    try (java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, username);

        try (java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {

                String storedPassword = rs.getString("password");
                boolean passwordMatches = false;
                boolean isBCryptHash = storedPassword != null
                    && storedPassword.matches("^\\$2[aby]\\$\\d\\d\\$.*");

                if (isBCryptHash) {
                    // Verify a BCrypt-hashed password.
                    try {
                        passwordMatches = BCrypt.checkpw(
                            password, storedPassword
                        );
                    } catch (IllegalArgumentException ex) {
                        passwordMatches = false;
                    }
                } else {
                    // Support existing plaintext passwords temporarily.
                    passwordMatches = password.equals(storedPassword);
                }

                if (passwordMatches) {

                    int userId = rs.getInt("id");
                    String loggedUsername = rs.getString("username");
                    String fullname = rs.getString("fullname");
                    String role = rs.getString("role");

                    
                    // Save logged-in user's information.
                    Session.userId = userId;
                    Session.username = loggedUsername;
                    Session.fullname = fullname;

                    System.out.println(
                        "Logged-in User ID: " + Session.userId
                    );
                    System.out.println(
                        "Logged-in Username: " + Session.username
                    );

                    // Close the result set before opening another screen.
                    rs.close();

                    if ("Admin".equalsIgnoreCase(role)) {
                        AdminDashboard admin = new AdminDashboard();
                        admin.setVisible(true);
                        this.dispose();
                    } else {
                        showWelcomeAndOpenHome();
                    }

                    return;

                } else {
                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Invalid username or password.",
                        "Login Failed",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                    );
                }

            } else {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Invalid username or password.",
                    "Login Failed",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Database error: " + e.getMessage(),
        "Database Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Unable to verify the password. Please contact the administrator.",
        "Login Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    
    }//GEN-LAST:event_loginActionPerformed

