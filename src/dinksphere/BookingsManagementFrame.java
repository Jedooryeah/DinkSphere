private void loadBookingCounts() {
    String sql = "SELECT "
            + "COUNT(*) AS total, "
            + "SUM(CASE WHEN status = 'Pending' THEN 1 ELSE 0 END) AS pending, "
            + "SUM(CASE WHEN status = 'Rejected' THEN 1 ELSE 0 END) AS rejected, "
            + "SUM(CASE WHEN status = 'Confirmed' THEN 1 ELSE 0 END) AS confirmed "
            + "FROM tbl_bookings";

    try (java.sql.Connection conn = DBConnection.connect()) {
        if (conn == null) {
            return;
        }

        try (java.sql.PreparedStatement pst = conn.prepareStatement(sql);
             java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                lblTotalText.setText(String.valueOf(rs.getInt("total")));
                lblPendingText.setText(String.valueOf(rs.getInt("pending")));
                lblRejectedText.setText(String.valueOf(rs.getInt("rejected")));
                lblConfirmedText.setText(String.valueOf(rs.getInt("confirmed")));
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to load booking counts: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}


private void loadBookings() {
    filterBookings();
}

private void filterBookings() {
    String keyword = txtSearchBookings.getText().trim();
    String selectedStatus = cmbStatusFilter.getSelectedItem().toString();

    String sql = "SELECT "
            + "COALESCE(NULLIF(b.customer_name, ''), "
            + "u.fullname, 'Walk-in Customer') AS customer, "
            + "b.court_name, b.booking_date, "
            + "b.start_time, b.end_time, b.status, b.payment_status "
            + "FROM tbl_bookings b "
            + "LEFT JOIN tbl_users u ON b.user_id = u.id "
            + "WHERE ("
            + "COALESCE(NULLIF(b.customer_name, ''), "
            + "u.fullname, 'Walk-in Customer') LIKE ? "
            + "OR b.court_name LIKE ?"
            + ") "
            + "AND (? = 'All Statuses' OR b.status = ?) "
            + "ORDER BY b.booking_date DESC, b.start_time ASC";

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblBookings.getModel();

    model.setRowCount(0);

    try (java.sql.Connection conn = DBConnection.connect()) {
        if (conn == null) {
            return;
        }

        try (java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {
            String searchValue = "%" + keyword + "%";

            pst.setString(1, searchValue);
            pst.setString(2, searchValue);
            pst.setString(3, selectedStatus);
            pst.setString(4, selectedStatus);

            try (java.sql.ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("customer"),
                        rs.getString("court_name"),
                        rs.getDate("booking_date"),
                        rs.getTime("start_time"),
                        rs.getTime("end_time"),
                        rs.getString("status"),
                        rs.getString("payment_status")
                    });
                }
            }
        }
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to filter bookings: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}



