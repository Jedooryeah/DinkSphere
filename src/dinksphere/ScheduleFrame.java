private void loadBookings() {
    String sql =
    "SELECT court_name, start_time, end_time " +
    "FROM tbl_bookings " +
    "WHERE booking_date = ? " +
    "AND status IN ('Pending', 'Confirmed')";

    String[] courts = {
        "Court Athena",
        "Court Apollo",
        "Court Atlas",
        "Court Aurora"
    };

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblBookings.getModel();

    model.setRowCount(0);

    java.text.SimpleDateFormat timeFormat =
        new java.text.SimpleDateFormat("h:mm a");

    try {
        java.sql.Connection conn = DBConnection.connect();

        if (conn == null) {
            return;
        }

        // Store the booking times for each court.
        java.util.Map<String, java.util.Set<Integer>> bookedSlots =
            new java.util.HashMap<>();

        for (String court : courts) {
            bookedSlots.put(court, new java.util.HashSet<>());
        }

        PreparedStatement pst = conn.prepareStatement(sql);

java.util.Date selectedDate = dateChooserSchedule.getDate();

if (selectedDate == null) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please select a date.",
        "Schedule",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

pst.setDate(1, new java.sql.Date(selectedDate.getTime()));

ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            String court = rs.getString("court_name");

            if (!bookedSlots.containsKey(court)) {
                continue;
            }

            java.sql.Time start = rs.getTime("start_time");
            java.sql.Time end = rs.getTime("end_time");

            java.util.Calendar current = java.util.Calendar.getInstance();
            current.setTime(start);

            java.util.Calendar finish = java.util.Calendar.getInstance();
            finish.setTime(end);

            while (current.before(finish)) {
                int hour = current.get(java.util.Calendar.HOUR_OF_DAY);
                bookedSlots.get(court).add(hour);
                current.add(java.util.Calendar.HOUR_OF_DAY, 1);
            }
        }

        rs.close();
        pst.close();
        conn.close();

        // Display hourly availability from 8 AM to 5 PM.
        for (int hour = 8; hour < 18; hour++) {
            java.util.Calendar time = java.util.Calendar.getInstance();
            time.set(java.util.Calendar.HOUR_OF_DAY, hour);
            time.set(java.util.Calendar.MINUTE, 0);
            time.set(java.util.Calendar.SECOND, 0);
            time.set(java.util.Calendar.MILLISECOND, 0);

            Object[] row = new Object[5];
            row[0] = timeFormat.format(time.getTime());

            for (int i = 0; i < courts.length; i++) {
                row[i + 1] = bookedSlots.get(courts[i]).contains(hour)
                    ? "Booked"
                    : "Available";
            }

            model.addRow(row);
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to load court availability: " + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

}

